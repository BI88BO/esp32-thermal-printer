/* 点密度补偿：一组 64 点里黑点越多，VH 掉得越狠，加热时间按 n² 往上补。
 * 数值 = 满 64 点黑时额外增加的百分比（0~150） */
#define DOTCOMP_PCT_DEFAULT  0
#define DOTCOMP_PCT_MAX      150
#define DOTCOMP_MIN_DOTS     4        // 少于这个数不补，稀疏点阵压降可以忽略

/* ---------- 冷态起步 + 热积累前馈（开环，不是闭环） ----------
 * 只解决一件事：冷头第一张偏灰、连打几张头热了偏黑。
 * 不测打印结果、不算误差、不反馈校正——把「已经往头里灌了多少能量」
 * 当作热状态的代理，提前把脉宽按热状态收回来。这属于前馈，不是闭环。
 *
 * 热状态 s ∈ [0,1000]：每行按「黑点数 × 实际脉宽 × repeat」注入，按一阶
 * 模型冷却；连续全黑、当前浓度打满 ≈ s=1000，停机放凉回 0。稀疏文字
 * 热积累小，s 也小，不会被误削——这是按能量而不是按行数算的原因。
 *
 * 三个数都由规格书推出，不需要实测标定：
 *   ① 表 4：25℃→45℃，540→460µs，斜率 = -80/20 = -4µs/℃ = -0.74%/℃。
 *   ② 表 4 只给到 45℃，和 sensor.cpp 一样不外推：25→45℃ 是 20℃，
 *      20 × 0.74% = 14.8%，取 15%。表 1 的 50℃ 工作上限由 50℃ 熔断
 *      / 45℃ 恢复兜底，不靠继续削能量硬撑。
 *   ③ 本机实测的温度效应明显强于表 4 标称（27℃ 时 300µs 完全不出色、
 *      60℃ 同脉宽明显出色），所以 15% 是「有规格书依据的保守下限」：
 *      宁可后段略深，也不能削到发灰——发灰比略深更难受。
 *      追求「全温域绝对一致」才需要闭环，这里不追求。
 * 唯一的模型量是过渡快慢 THERM_WINDOW_ROWS=64 行（一行约 30.7ms，≈2s，
 * 与打印头铝基板热时间常数同量级）。它只决定爬升速度，不影响起点、
 * 终点和 15% 上限，32~128 之间差别很小，不需要现场调。
 *
 * 冷态起步给 125%，随 s 平滑退到 0，取代 build 82「固定前 24 行 ×1.25」
 * 的硬切（第 25 行会留一道浓淡分界）。s=0 → 1.25×（与 82 起步一致），
 * s=1000 → 0.85×（1.0 再削 15%）。整条曲线单调连续，没有台阶。
 * 连打第二张时 s 还留着，起步补偿自动减少、削减自动保持，
 * 所以不会「越打越黑、放凉又回退」。 */
#define THERM_TRIM_MAX_PCT      15   // 稳态最多削 15%（表 4：25→45℃，不外推）
#define THERM_WINDOW_ROWS       64   // 一阶热模型窗口（行），只影响过渡快慢
#define THERM_STATE_FULL       1000  // 热状态满量程（归一化到 1000 = 全黑行、基准浓度、1 遍）

#define COLD_START_PCT          125  // 冷头起步能量百分比（随 s 平滑退出）
#define COLD_START_TEMP_C       30   // 头温达到这个值就不再给起步补偿

/* 能量硬上限：冷头满补后的绝对天花板。
 *   HEAT_US_MAX(4000) 是「App 浓度滑杆能设到多大」；
 *   本值再加上冷头的 ×1.25，是「单个脉冲最长能有多长」。
 * 为什么要单独定义：冷头补偿在点补偿之前生效，两者叠加后很容易顶到
 * 4000 以上。build 88 及以前只有点补偿分支做了钳位，dotcomp=0（标准档）
 * 反而不钳，冷头时能到 5000µs；而开了点补偿的「加深档」却被钳回 4000，
 * 于是出现「加深比标准更淡」的反向效果。
 * 现在统一在 core/heat_model.cpp 的最后一步按本值钳位，所有分支同一个出口：
 *   标准档冷头 4600 → 4600（不变）
 *   加深档冷头 4600+2760 → 5000（比标准更黑，符合档位语义）
 * 用推导式而不是写死 5000：改 COLD_START_PCT 时天花板自动跟随，不会漏改。 */
#define HEAT_US_ABS_MAX         ((HEAT_US_MAX) * (COLD_START_PCT) / 100)

/* 整组全白时跳过选通（只省时间，不改任何有内容点的能量）。
 * build 84 重新开启：group_black() 是 16 项 popcount 查表，逐行统计已被
 * 热积累前馈复用并验证；空白组本来就没有驱动管导通、不耗电，
 * 跳过只是省掉 delayMicroseconds(t) 的忙等。
 * slot_pad() 仍会把拍槽补到 min_beat_us，走纸节拍不变、不会丢步；
 * 行级过热检查在 group_black() 之前，跳过也不影响熔断覆盖。
 * 稀疏文字 / 留白行收益最大（6 组里 4 组全空时约 2 倍多），全黑块无变化。
 * 若出现「整行不加热」，第一个要关的就是这个宏。 */
#define SKIP_BLANK_GROUPS    1

/* ---------- 打印队列 ---------- */
#define LINE_QUEUE_LEN  48           // 48 行缓冲 = 6mm
#define RX_TIMEOUT_MS   3000         // 断流超时

/* ---------- 过热暂停 / 自动续打 ----------
 * 打印中触发 50℃ 熔断时不再 command_end_job() 杀掉作业，而是关 VH、停走纸、
 * 保留 lineQ 与 doneLines，等 NTC 降到 OVERHEAT_RECOVER_C(45℃) 后
 * 重新预热 VH，从下一行继续打。App 不用重发、不用重新点打印，
 * 长图才不会因为几次过热就永远从头开始。
 * 暂停期间 RX_TIMEOUT_MS 必须冻结（见 main.cpp），否则 3 秒就把作业超时掉。
 * 这是兜底上限：正常 50→45℃ 一般几十秒；超时或 NTC 失效才真正中止并报错，
 * 避免传感器坏掉时无限等待。 */
