/* ---------- 加热能量（机芯规格书 的 3.2 / 3.3 / 3.4） ----------
 * 规格书在 VH=7.2V 下给的是一套自洽数据，代入 3.4 公式可完整验算：
 *   I0(单点) = VH/(Rcom+Ric+Rlead+Rav) = 7.2/(0.05+6+10+176) = 0.0375A
 *   P0 = I0²·Rav = 0.247 W/dot          ≈ 表 4 的 0.24 W/dot
 *   64 点总电流 = 64×0.0375 = 2.40A     ≈ 表 4 的 I0 = 2.4A
 *   回路等效电阻 = 7.2/2.4 = 3.0Ω
 *   Ton(25℃) = 0.13mJ/0.247W = 525µs   ≈ 表 4 的 540µs
 *   Ton(E0)  = 0.20mJ/0.247W = 808µs   ≈ 833µs
 * 表 3：E0=0.20 mJ/dot 是绝对最大额定；VH 正常 7.2V、最大 8.5V。
 * 表 4 推荐 Ton：5℃ 670µs / 25℃ 540µs / 45℃ 460µs，条件均为
 *   S.L.T=1.25ms/line 循环打印、Rav=176Ω、Vdd=5V、64 点同时加热。
 * 表 6「VH 最小 3.13V」是允许施加的电压下限，不是本机实测电压。
 *
 * 【必须说清】本机静态 VH 实测 7.2V，所以上面的标称折算适用：
 *   4000µs 按 P0 折算 = 0.989 mJ/dot = E0 的 4.95 倍，属超额定运行，
 *   不能说"没超 E0"。build 78~80 曾把整页钳到 800µs，27℃ 冷态几乎全白，
 *   这只能证明「本机在 7.2V 下的实际发色效率远低于规格书模型」，
 *   不能反推「本机 VH 只有 3.3V」——那是把表 6 下限当成了实测值。
 *   尚未定量、也未证实的原因：
 *     ① 表 4 隐含 2.4A 脉冲电流能力；供电回路只要多出约 3Ω 内阻，
 *        带载时头端 VH 就会塌掉一半，P0∝V² 掉到 1/4（实测"越慢越清晰"
 *        支持这条：慢速给输出电容更多回充时间）
 *     ② FPC 接触电阻 / 拆机头老化，使 Rcom+Ric+Rlead 远大于公式的 16Ω
 *     ③ 【已排除】原理图 FPC2 的「逻辑电源端」接 3V3，VIH=0.8×3.3=2.64V，
 *        ESP32 的 3.3V GPIO 满足要求，STB 电平不足导致驱动管导通电阻变大
 *        这条不成立（表 6 的 Vdd=5V 只是典型值，本板没用 5V）
 *     ④ 规格书是 S.L.T=1.25ms/line 连续打印（有热积累），本机一行约
 *        35ms，慢 28 倍，热量散失多，起点温度更低
 * 现状：能量上限 HEAT_US_MAX=4000µs，安全仅由 50℃ 熔断 + 45℃ 恢复
 *   兜底，不构成规格书级合规保证。 */

