/* ============================================================================
 * 文件：core/temp_comp.h
 * 层次：纯逻辑层 / 温度补偿（不碰 ADC，可单独阅读理解）
 * 职责：把「实测头温」换算成「加热时间系数」，按规格书表 4 查表插值。
 * 对应原工程：无。原工程没有温度补偿，温度只用于 >65℃ 中止。
 *
 * 规格书 V1.3 表 4（PDF 第 7 页 / 印刷第 6 页），条件 VH=7.2V、64 点同时加热：
 *   5℃   0.16 mJ/dot (Ton 0.67ms)
 *   25℃  0.13 mJ/dot (Ton 0.54ms)
 *   45℃  0.11 mJ/dot (Ton 0.46ms)
 * 归一化到 25℃：1.231 / 1.000 / 0.846 → 斜率约 -0.74%/℃
 *
 * 45℃ 以上**不外推**：表 4 只给到 45℃，再往上交给 50℃ 熔断。
 * 以前这里外推到 0.80，结果"连打几张头温上来"时又砍 20% 能量，
 * 实测表现为越打越淡、拉满浓度也追不回第一张。
 *
 * 依赖：config.h（HEAT_US_MIN / HEAT_US_MAX）
 * 被谁用：hal/sensor.cpp（sensor_heat_us_compensated）
 * ========================================================================== */
#ifndef TEMP_COMP_H
#define TEMP_COMP_H

#include <Arduino.h>

/* 按头温把基准脉宽缩放成实际脉宽，并钳到 [HEAT_US_MIN, HEAT_US_MAX]。
 * temp_c < 0 表示 NTC 失效：原样返回，不做补偿（失效时宁可保持基准，
 * 也不要凭空加减能量） */
uint16_t temp_comp_heat_us(uint16_t base_us, int8_t temp_c);

/* 只取系数（×1000，即 1231 表示 1.231），给日志和自检页显示用 */
uint16_t temp_comp_permille(int8_t temp_c);

#endif
