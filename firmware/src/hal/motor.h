#ifndef MOTOR_H
#define MOTOR_H

#include <Arduino.h>

/* ============================================================================
 * 文件：hal/motor.h
 * 层次：硬件抽象层 (HAL) / 步进电机
 * 职责：相序表、单拍推进、整段走纸、相位对齐。
 * 对应原工程：src/hal/em_motor.h + src/hal/em_motor.cpp
 *
 * 两种驱动方式（只换相序，硬件不用改）：
 *   1-2 相半步：8 个状态全走，一拍 4.5° = 0.03125mm，一行 4 拍；
 *               其中两个「单相」状态在 TC1508S 上是短接制动，力矩会掉，
 *               纸轻微一顿，纵向横纹就是这么来的。
 *   双相整步 ：只取偶数下标（都是两相通电），一拍 9° = 0.0625mm，
 *               一行 2 拍，力矩恒定、拍率减半，但绕组发热高约 1/3。
 *
 * 并发约定：本模块不持有互斥量！调用方（hal/printer.cpp）必须先拿到
 *           hw_mtx 再调。原因是走纸和打印行都在同一个作业里串行发生，
 *           锁的粒度是「整个作业」，不是「一拍」。
 *
 * 被谁用：hal/printer.cpp
 * ========================================================================== */

/* 上电初始化：配置 4 个相位引脚并全部拉低（绕组断电） */
void motor_init(void);

/* 走一拍。dual=true 用双相整步（stride 2），false 用 1-2 相半步（stride 1） */
void motor_step(bool dual);

/* 所有相位引脚拉低，作业结束 / 走纸结束都要调，避免绕组一直通电发热 */
void motor_off(void);

/* 把相位对齐到「两相通电」状态（seq_pos &= 6）。
 * 走纸固定用 8 状态半步，会把相位留在奇数位；双相模式若从单相起步力矩差 */
void motor_align_dual(void);

/* 连续走纸 beats 拍，固定用 1-2 相半步（0.03125mm/拍）。
 * 内部每拍让出 1 个 tick 再用 micros() 补齐，节拍不缩短、RTOS 不饿死。
 * 调用者必须持锁；1 拍 = 0.03125mm，240 拍 ≈ 7.5mm */
void motor_feed(uint32_t beats);

#endif
